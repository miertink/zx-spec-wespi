"""Builds main/turbo_bin.h from main/asm/turbo.asm.

The routine is placed by the ESP32 at an address known only at run time
(end of each BASIC program), so it is assembled twice, at two bases, and
every 16-bit word whose high byte moves with the base is an address to
relocate. Also exports the offsets of the labels the firmware needs.

Usage:  python tools/mkturbo.py   (needs sjasmplus on PATH or at SJASM)
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASM = os.path.join(ROOT, "main", "asm", "turbo.asm")
OUT = os.path.join(ROOT, "main", "turbo_bin.h")
SJASM = os.environ.get("SJASM", r"C:\Espressif\tools\sjasmplus\sjasmplus-1.24.0.win\sjasmplus.exe")
B0, B1 = 0x8000, 0x9100
LABELS = ["entry", "req"]


def assemble(base):
    out = os.path.join(ROOT, "build", "turbo_%04x" % base)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run([SJASM, "-DBASE=0x%04X" % base, "--raw=" + out + ".bin", "--sym=" + out + ".sym", ASM],
                   check=True, stdout=subprocess.DEVNULL)
    code = open(out + ".bin", "rb").read()
    syms = {}
    for line in open(out + ".sym", encoding="latin-1"):
        m = re.match(r"\s*(\w+):\s+EQU\s+0x([0-9A-Fa-f]+)", line)
        if m:
            syms[m.group(1)] = int(m.group(2), 16)
    return code, syms


c0, s0 = assemble(B0)
c1, s1 = assemble(B1)
assert len(c0) == len(c1)
relocs = []
i = 0
while i < len(c0):
    if c0[i] != c1[i]:
        # a differing high byte: the address word starts one byte before
        assert i > 0 and c0[i - 1] == c1[i - 1] and c1[i] - c0[i] == (B1 - B0) >> 8, "not an address at %d" % i
        w = c0[i - 1] | c0[i] << 8
        assert B0 <= w < B0 + len(c0) + 16, "address 0x%04X out of the code at %d" % (w, i)
        relocs.append(i - 1)
    i += 1

with open(OUT, "w") as f:
    f.write("/* Generated by tools/mkturbo.py from main/asm/turbo.asm: do not edit. */\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("#define TURBO_ORG 0x%04X        /* address the code below is assembled for */\n" % B0)
    for name in LABELS:
        f.write("#define TURBO_OFS_%s %d\n" % (name.upper(), s0[name] - B0))
    f.write("\nstatic const uint8_t turbo_code[%d] = {" % len(c0))
    for k, b in enumerate(c0):
        f.write(("\n    " if k % 16 == 0 else " ") + "0x%02X," % b)
    f.write("\n};\n\n/* offsets of the 16-bit addresses to relocate */\n")
    f.write("static const uint16_t turbo_reloc[%d] = {" % len(relocs))
    f.write(", ".join(str(r) for r in relocs))
    f.write("};\n")
print("turbo: %d bytes, %d relocations, entry %d, req %d" % (len(c0), len(relocs), s0["entry"] - B0, s0["req"] - B0))
